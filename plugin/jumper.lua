if vim.g.loaded_jumper == 1 then return end
vim.g.loaded_jumper = 1

-- check if jumper is installed
if vim.fn.executable("jumper") ~= 1 then
    vim.notify(
        "jumper is not installed. Please follow the instructions at https://github.com/homerours/jumper",
        vim.log.levels.ERROR)
    return
end

local uv = vim.uv or vim.loop
local j = require('jumper')
local z_config = { jumper_max_results = 1, jumper_colors = false }

-- Compatibility shim for vim.system (introduced in Neovim 0.10)
local system = vim.system or function(cmd, opts)
    vim.fn.jobstart(cmd, {
        detach = opts and opts.detach or false,
        on_exit = function() end,
    })
end

-- update the database (files or directories)
local function update_database(path, weight, type)
    -- Validate path
    if not path or path == "" then return end

    -- Normalize path
    path = vim.fs.normalize(path)

    -- exclude git files and paths with ':' (often temporary buffers generated by plugins)
    if not (string.find(path, "/.git/") or string.find(path, ":")) then
        system(
            { "jumper", "update", "--type=" .. type, "-w", tostring(weight), path },
            { detach = true }
        )
    end
end

-- Update database whenever a file is opened
vim.api.nvim_create_autocmd({ "BufNewFile", "BufReadPre" }, {
    pattern = { "*" },
    callback = function(ev)
        local filename = vim.api.nvim_buf_get_name(ev.buf)
        update_database(filename, 1.0, 'files')
    end
})

-- Update database whenever a file is modified
vim.api.nvim_create_autocmd({ "BufWritePre" }, {
    pattern = { "*" },
    callback = function(ev)
        local buf_modified = vim.bo[ev.buf].modified
        if buf_modified then
            local filename = vim.api.nvim_buf_get_name(ev.buf)
            update_database(filename, 0.3, 'files')
        end
    end
})

-- Update database whenever a current directory has changed
vim.api.nvim_create_autocmd({ "DirChanged" }, {
    pattern = { "*" },
    callback = function()
        update_database(uv.cwd(), 1.0, "directories")
    end
})

local function make_completion_function(type)
    return function(prompt, _, _)
        local cmd = j.make_command(type,
            { jumper_max_results = j.config.jumper_max_completion_results, jumper_colors = false },
            prompt)
        return vim.fn.systemlist(cmd)
    end
end

local function z(opts)
    local query = opts.args and opts.args ~= "" and vim.fs.normalize(opts.args) or ""
    local cmd = j.make_command("directories", z_config, query)
    local dir = vim.fn.systemlist(cmd)
    if dir[1] then
        vim.cmd.cd(dir[1])
    else
        vim.print("No match found.")
    end
end

local function zf(opts)
    local query = opts.args and opts.args ~= "" and vim.fs.normalize(opts.args) or ""
    local cmd = j.make_command("files", z_config, query)
    local dir = vim.fn.systemlist(cmd)
    if dir[1] then
        vim.cmd.edit(dir[1])
    else
        vim.print("No match found.")
    end
end

-- Functions to jump from the command line:
vim.api.nvim_create_user_command('Z', z,
    {
        nargs = '*',
        complete = make_completion_function('directories')
    })
vim.api.nvim_create_user_command('Zf', zf,
    {
        nargs = '*',
        complete = make_completion_function('files')
    })
